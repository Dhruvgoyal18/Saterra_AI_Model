"""Phase A (production): upload the bucket to a *private* Hugging Face Hub
dataset repo.

Requires network access and an HF token with write access -- neither is
available in the sandboxed environment this project was built in (verified:
`pip install` against PyPI fails with a DNS resolution error there, and no
HF token is configured). This script is written and ready to run on a
machine that has both; it was not executed as part of this build.

Usage:
  export HF_TOKEN=hf_xxx                       # a token with write access
  export HF_DATASET_REPO=your-username/dapi-artifact-images
  python scripts/upload_to_hf.py

Uploads, per image: manifest.json (once, at repo root), image_N/display.png
(from bucket_staging/, already generated by prepare_display_images.py), and
image_N/original.ome.tiff (streamed directly from ../DAPI_images/ -- not
duplicated into bucket_staging/ first).
"""

import os
from pathlib import Path

from huggingface_hub import HfApi

ROOT = Path(__file__).resolve().parent.parent
ORIGINALS_DIR = ROOT.parent / "DAPI_images"
BUCKET_DIR = ROOT / "backend" / "bucket_staging"

ALL_IDS = range(1, 9)


def main() -> None:
    token = os.environ.get("HF_TOKEN")
    repo_id = os.environ.get("HF_DATASET_REPO")
    if not token or not repo_id:
        raise SystemExit("Set HF_TOKEN and HF_DATASET_REPO environment variables first.")

    api = HfApi(token=token)

    print(f"Creating (or reusing) private dataset repo: {repo_id}")
    api.create_repo(repo_id=repo_id, repo_type="dataset", private=True, exist_ok=True)

    manifest_path = BUCKET_DIR / "manifest.json"
    if not manifest_path.exists():
        raise SystemExit(f"No manifest at {manifest_path} -- run prepare_display_images.py first.")

    print("Uploading manifest.json...")
    api.upload_file(
        path_or_fileobj=str(manifest_path),
        path_in_repo="manifest.json",
        repo_id=repo_id,
        repo_type="dataset",
    )

    for image_id in ALL_IDS:
        display_path = BUCKET_DIR / f"image_{image_id}" / "display.png"
        original_path = ORIGINALS_DIR / f"Image_{image_id}.ome.tiff"

        print(f"Uploading image_{image_id}/display.png...")
        api.upload_file(
            path_or_fileobj=str(display_path),
            path_in_repo=f"image_{image_id}/display.png",
            repo_id=repo_id,
            repo_type="dataset",
        )

        print(f"Uploading image_{image_id}/original.ome.tiff (this one is large, ~150-180MB)...")
        api.upload_file(
            path_or_fileobj=str(original_path),
            path_in_repo=f"image_{image_id}/original.ome.tiff",
            repo_id=repo_id,
            repo_type="dataset",
        )

    print(f"\nDone. Set STORAGE_BACKEND=hf, HF_TOKEN, HF_DATASET_REPO={repo_id} on the backend to use it.")


if __name__ == "__main__":
    main()
